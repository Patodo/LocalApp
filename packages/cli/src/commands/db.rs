const PLATFORM_TYPE_HINT: &str =
    "For platform data types (users, groups, roles), import from @localapp/sdk-react";

#[derive(Debug)]
pub(crate) struct ColumnInfo {
    pub name: String,
    pub sqlite_type: String,
    pub not_null: bool,
    pub primary_key: bool,
}

pub fn types(output: &str) -> Result<(), String> {
    let cwd = std::env::current_dir().map_err(|e| format!("Failed to get cwd: {e}"))?;
    let db_path = cwd.join(".localapp").join("dev.db");
    if !db_path.exists() {
        return Err("dev.db not found. Run localapp db migrate first.".to_string());
    }

    let conn = Connection::open(&db_path).map_err(|e| format!("Failed to open dev.db: {e}"))?;
    let tables = user_tables(&conn)?;
    let mut content = String::new();
    content.push_str("// Generated by localapp db types.\n");
    content.push_str("// ");
    content.push_str(PLATFORM_TYPE_HINT);
    content.push_str("\n\n");

    if tables.is_empty() {
        content.push_str("// No user tables found in dev.db. Run localapp db migrate first.\n");
    } else {
        for table in &tables {
            content.push_str(&render_interface(&conn, table)?);
            content.push('\n');
        }
    }

    let output_path = cwd.join(output);
    if let Some(parent) = output_path.parent() {
        fs::create_dir_all(parent)
            .map_err(|e| format!("Failed to create output directory: {e}"))?;
    }
    fs::write(&output_path, content).map_err(|e| format!("Failed to write {output}: {e}"))?;

    if tables.is_empty() {
        println!("No user tables found in dev.db. Run localapp db migrate first.");
    } else {
        println!("Generated {} interfaces to {}", tables.len(), output);
    }
    Ok(())
}

pub fn migrate() -> Result<(), String> {
    let cwd = std::env::current_dir().map_err(|e| format!("Failed to get cwd: {e}"))?;
    let localapp_dir = cwd.join(".localapp");
    fs::create_dir_all(&localapp_dir).map_err(|e| format!("Failed to create .localapp: {e}"))?;
    let db_path = localapp_dir.join("dev.db");
    let mut conn = Connection::open(&db_path).map_err(|e| format!("Failed to open dev.db: {e}"))?;
    let applied = apply_migrations(&mut conn, &cwd.join("migrations"))?;
    if applied.is_empty() {
        println!("No pending migrations");
    } else {
        for filename in &applied {
            println!("Applied {filename}");
        }
        println!("{} migrations applied", applied.len());
    }
    Ok(())
}

pub fn reset() -> Result<(), String> {
    let cwd = std::env::current_dir().map_err(|e| format!("Failed to get cwd: {e}"))?;
    let localapp_dir = cwd.join(".localapp");
    fs::create_dir_all(&localapp_dir).map_err(|e| format!("Failed to create .localapp: {e}"))?;
    let db_path = localapp_dir.join("dev.db");
    if db_path.exists() {
        fs::remove_file(&db_path).map_err(|e| format!("Failed to remove existing dev.db: {e}"))?;
    }

    let mut conn =
        Connection::open(&db_path).map_err(|e| format!("Failed to create dev.db: {e}"))?;
    let applied = apply_migrations(&mut conn, &cwd.join("migrations"))?;
    ensure_applied_migrations_table(&conn)?;

    let migration_applied = fs::read(&db_path).ok();
    let seed_path = cwd.join("db").join("seeds").join("dev.sql");
    if seed_path.exists() {
        let sql = fs::read_to_string(&seed_path)
            .map_err(|e| format!("Failed to read db/seeds/dev.sql: {e}"))?;
        let count = count_sql_statements(&sql);
        let tx = conn
            .transaction()
            .map_err(|e| format!("Failed to start seed transaction: {e}"))?;
        if let Err(error) = tx.execute_batch(&sql) {
            drop(tx);
            drop(conn);
            if let Some(bytes) = migration_applied {
                fs::write(&db_path, bytes)
                    .map_err(|e| format!("Failed to restore dev.db after seed failure: {e}"))?;
            }
            return Err(format!(
                "Seed failed. dev.db rolled back to migration-applied state. {error}"
            ));
        }
        tx.commit()
            .map_err(|e| format!("Failed to commit seed: {e}"))?;
        println!("Applied seed: {count} SQL statements");
    } else {
        println!("No seed file found at db/seeds/dev.sql");
    }

    println!("Applied {} migrations", applied.len());
    Ok(())
}

